"""2級 教科書 第3章「2変数データの記述」の数値の検算。"""
import numpy as np
from bookcheck import Book

b = Book("g2", 3)
x = np.array([2, 3, 4, 5, 5, 6, 7, 8, 9, 11])
y = np.array([48, 58, 50, 60, 66, 57, 72, 64, 79, 76])
z = np.array([3.5, 2, 4, 2.5, 1.5, 3, 2, 2.5, 1, 2])
c1 = b.chart(1)
b.check("図1のデータが本文の表と一致", c1["x"] == list(x) and c1["y"] == list(y), "")
b.check("表の勉強時間の行", b.has("| 勉強時間 $x$（時間） | 2 | 3 | 4 | 5 | 5 | 6 | 7 | 8 | 9 | 11 |"), "")
b.check("表の点数の行", b.has("| 点数 $y$ | 48 | 58 | 50 | 60 | 66 | 57 | 72 | 64 | 79 | 76 |"), "")
b.num("x の平均", x.mean(), "6")
b.num("y の平均", y.mean(), "63")
sxy = ((x - x.mean()) * (y - y.mean())).sum()
b.num("偏差の積の合計", sxy, "225")
b.num("共分散（n−1）", sxy / 9, "25")
b.num("分に直した共分散", ((60 * x - 60 * x.mean()) * (y - y.mean())).sum() / 9, "1500")
b.num("Σ(x−x̄)²", ((x - x.mean()) ** 2).sum(), "70")
b.num("Σ(y−ȳ)²", ((y - y.mean()) ** 2).sum(), "980")
r = np.corrcoef(x, y)[0, 1]
b.num("相関係数", r, "0.859")
b.num("分に直した相関係数", np.corrcoef(60 * x, y)[0, 1], "0.859")
b.check("右上・左下の点が多い", sum((x - 6) * (y - 63) > 0) > sum((x - 6) * (y - 63) < 0), (sum((x - 6) * (y - 63) > 0), sum((x - 6) * (y - 63) < 0)))
u = np.arange(1, 6)
b.check("y=(x−3)² のデータ 4,1,0,1,4", list((u - 3) ** 2) == [4, 1, 0, 1, 4], "")
b.check("y=(x−3)² の相関係数は 0", abs(np.corrcoef(u, (u - 3) ** 2)[0, 1]) < 1e-12, np.corrcoef(u, (u - 3) ** 2)[0, 1])
b.num("外れ値を加えた相関係数", np.corrcoef(np.append(x, 10), np.append(y, 30))[0, 1], "0.257")
R = np.corrcoef([x, y, z])
b.num("勉強時間とスマホ", R[0, 2], "-0.527")
b.num("点数とスマホ", R[1, 2], "-0.857")
b.check("相関係数行列の行", b.has("| 勉強時間 | 1 | 0.859 | −0.527 |") and b.has("| 点数 | 0.859 | 1 | −0.857 |") and b.has("| スマホ時間 | −0.527 | −0.857 | 1 |"), "")
# 偏相関
pc = lambda rxy, rxz, ryz: (rxy - rxz * ryz) / np.sqrt((1 - rxz ** 2) * (1 - ryz ** 2))
b.check("アイスと水難の偏相関は 0", abs(pc(0.6, 0.8, 0.75)) < 1e-12, pc(0.6, 0.8, 0.75))
# 層別
c2 = b.chart(2)
sa, sb = c2["series"]
ra = np.corrcoef(sa["x"], sa["y"])[0, 1]
rb = np.corrcoef(sb["x"], sb["y"])[0, 1]
b.num("郊外の相関", ra, "-1.00")
b.num("都心の相関", rb, "-1.00")
b.check("層の中は負", ra < 0 and rb < 0, (ra, rb))
b.num("合わせた相関", np.corrcoef(sa["x"] + sb["x"], sa["y"] + sb["y"])[0, 1], "0.665")
# クロス表
b.check("クロス表の合計", 12 + 138 == 150 and 14 + 36 == 50 and 12 + 14 == 26 and 138 + 36 == 174 and 150 + 50 == 200, "")
b.num("食べる生徒の遅刻率", 12 / 150, "0.08")
b.num("食べない生徒の遅刻率", 14 / 50, "0.28")
b.num("全体の遅刻率 %", 26 / 200 * 100, "13")
b.num("期待度数（食べる・遅刻）", 150 * 26 / 200, "19.5")
b.num("期待度数（食べない・遅刻）", 50 * 26 / 200, "6.5")
# シンプソン（塾）
for name, (a1, n1), (a2, n2), shown in [("A", (12, 40), (112, 160), ("30%", "70%", "62%")), ("B", (56, 160), (30, 40), ("35%", "75%", "43%"))]:
    b.num(f"塾{name} 難関", a1 / n1, shown[0])
    b.num(f"塾{name} 標準", a2 / n2, shown[1])
    b.num(f"塾{name} 合計", (a1 + a2) / (n1 + n2), shown[2])
    b.check(f"塾{name} 合計の分数", b.has(f"{a1 + a2}/{n1 + n2}"), f"{a1 + a2}/{n1 + n2}")
b.check("層ごとには B が 5 ポイント上", abs((56 / 160 - 12 / 40) - 0.05) < 1e-12 and abs((30 / 40 - 112 / 160) - 0.05) < 1e-12, "")
b.check("加重平均の式（A）", abs(0.30 * 40 / 200 + 0.70 * 160 / 200 - 0.62) < 1e-12, "")
b.check("加重平均の式（B）", abs(0.35 * 160 / 200 + 0.75 * 40 / 200 - 0.43) < 1e-12, "")
# 章末問題
px, py = np.array([1, 2, 3, 4, 5]), np.array([2, 3, 5, 4, 6])
b.check("問1 偏差の積の合計 9", ((px - 3) * (py - 4)).sum() == 9, "")
b.check("問1 Σ(y−ȳ)² = 10", ((py - 4) ** 2).sum() == 10, "")
b.num("問1 相関係数", np.corrcoef(px, py)[0, 1], "0.9")
b.num("問3 分母", np.sqrt(0.75 * 0.64), "0.693")
b.num("問3 偏相関", pc(0.6, 0.5, 0.6), "0.43")
for name, (a1, n1), (a2, n2), shown in [("T", (18, 20), (48, 80), ("90%", "60%", "66%")), ("C", (64, 80), (10, 20), ("80%", "50%", "74%"))]:
    b.num(f"問4 {name} 軽症", a1 / n1, shown[0])
    b.num(f"問4 {name} 重症", a2 / n2, shown[1])
    b.num(f"問4 {name} 合計", (a1 + a2) / (n1 + n2), shown[2])
b.done()
