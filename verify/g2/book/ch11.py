"""2級 教科書 第11章「推定」の数値の検算（信頼区間の被覆率はシミュレーションでも確かめる）。"""
import numpy as np
from bookcheck import Book
from scipy import stats as st

b = Book("g2", 11)
x = np.array([501.2, 499.8, 500.6, 502.1, 498.9, 500.3, 501.5, 499.4, 500.9, 501.3])
b.check("本文のデータ", b.has("501.2, 499.8, 500.6, 502.1, 498.9, 500.3, 501.5, 499.4, 500.9, 501.3"), "")
m, s, S = x.mean(), x.std(ddof=1), ((x - x.mean()) ** 2).sum()
b.num("平均", m, "500.6")
b.num("偏差平方和", S, "9.06")
b.num("不偏分散", s ** 2, "1.007")
b.num("s", s, "1.003")
t9 = st.t.ppf(0.975, 9)
b.num("t(9)", t9, "2.262")
b.num("標準誤差", s / np.sqrt(10), "0.317")
b.num("誤差の幅", t9 * s / np.sqrt(10), "0.718")
b.num("下限", m - t9 * s / np.sqrt(10), "499.88")
b.num("上限", m + t9 * s / np.sqrt(10), "501.32")
b.num("下限（1 桁）", m - t9 * s / np.sqrt(10), "499.9")
b.check("500 は区間の中", m - t9 * s / np.sqrt(10) < 500 < m + t9 * s / np.sqrt(10), "")
b.num("分散既知の下限", m - 1.96 / np.sqrt(10), "499.98")
b.num("分散既知の上限", m + 1.96 / np.sqrt(10), "501.22")
b.num("99% の点", st.norm.ppf(0.995), "2.576")
# n で割った分散の期待値
rng = np.random.default_rng(11)
y = rng.normal(size=(200000, 5))
b.check("n=5 で n 割りの期待値は 0.8σ²（シミュレーション）", abs(y.var(1).mean() - 0.8) < 0.01 and abs(y.var(1, ddof=1).mean() - 1) < 0.01, (y.var(1).mean(), y.var(1, ddof=1).mean()))
# 被覆率
z = rng.normal(500.6, 1, (100000, 10))
mm, ss = z.mean(1), z.std(1, ddof=1)
cov = np.mean(np.abs(mm - 500.6) <= t9 * ss / np.sqrt(10))
b.check("t 区間の被覆率 ≈ 95%（シミュレーション）", abs(cov - 0.95) < 0.004, cov)
# 母分散
b.num("χ²_0.025(9)", st.chi2.ppf(0.975, 9), "19.02")
b.num("χ²_0.975(9)", st.chi2.ppf(0.025, 9), "2.700")
b.num("分散の下限", S / 19.02, "0.476")
b.num("分散の上限", S / 2.700, "3.36")
b.num("sd の下限", np.sqrt(S / 19.02), "0.69")
b.num("sd の上限", np.sqrt(S / 2.700), "1.83")
# 比率
se = np.sqrt(0.52 * 0.48 / 1000)
b.num("比率の SE", se, "0.0158")
b.num("比率の下限", 0.52 - 1.96 * se, "0.489")
b.num("比率の上限", 0.52 + 1.96 * se, "0.551")
# 2 標本
sp2 = (11 * 64 + 9 * 49) / 20
b.num("704", 11 * 64, "704")
b.num("441", 9 * 49, "441")
b.num("プールした分散", sp2, "57.25")
se2 = np.sqrt(sp2 * (1 / 12 + 1 / 10))
b.num("差の SE", se2, "3.240")
b.num("t(20)", st.t.ppf(0.975, 20), "2.086")
b.num("誤差の幅", 2.086 * se2, "6.76")
b.num("下限", 7 - 2.086 * se2, "0.24")
b.num("上限", 7 + 2.086 * se2, "13.76")
sep = np.sqrt(0.3 * 0.7 / 400 + 0.22 * 0.78 / 500)
b.num("比率の差の SE", sep, "0.0295")
b.num("比率の差の下限", 0.08 - 1.96 * sep, "0.022")
b.num("比率の差の上限", 0.08 + 1.96 * sep, "0.138")
# 標本の大きさ
b.num("n（±3 ポイント）", (1.96 / 0.03) ** 2 * 0.25, "1067.1")
b.check("切り上げ 1068", int(np.ceil((1.96 / 0.03) ** 2 * 0.25)) == 1068, "")
b.num("±1.5 ポイント", (1.96 / 0.015) ** 2 * 0.25, "4300", tol=50)
b.num("有限母集団修正", np.sqrt((4000 - 200) / 3999), "0.975")
# 章末問題
b.num("問1 SE", 20 / 4, "5")
b.num("問1 t(15)", st.t.ppf(0.975, 15), "2.131")
b.num("問1 幅", 2.131 * 5, "10.66")
b.num("問1 下限", 302 - 2.131 * 5, "291.34")
b.num("問1 上限", 302 + 2.131 * 5, "312.66")
b.num("問2 SE", np.sqrt(0.2 * 0.8 / 400), "0.02")
b.num("問2 下限", 0.2 - 1.96 * 0.02, "0.161")
b.num("問2 上限", 0.2 + 1.96 * 0.02, "0.239")
b.num("問2 n", (1.96 / 0.02) ** 2 * 0.16, "1536.6")
b.num("問3 下限", 36 / 19.02, "1.89")
b.num("問3 上限", 36 / 2.700, "13.3")
b.done()
