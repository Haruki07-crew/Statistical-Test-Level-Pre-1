"""2級 教科書 第5章「時系列データ」の数値の検算。"""
import numpy as np
from bookcheck import Book

b = Book("g2", 5)
y = np.array([20, 28, 40, 24, 23, 31, 44, 27, 26, 35, 48, 30.])
c1 = b.chart(1)
b.check("図1の売上が表と一致", c1["series"][0]["y"] == list(y), "")
for i, row in enumerate(y.reshape(3, 4)):
    b.check(f"表の {i + 1} 年目", b.has(f"| {i + 1} 年目 | " + " | ".join(str(int(v)) for v in row) + f" | {int(row.sum())} |"), row)
tot = y.reshape(3, 4).sum(1)
ma = [(0.5 * y[t - 2] + y[t - 1] + y[t] + y[t + 1] + 0.5 * y[t + 2]) / 4 for t in range(2, 10)]
b.check("図1の移動平均が計算と一致", c1["series"][1]["y"][2:10] == [round(v, 3) for v in ma] and c1["series"][1]["y"][:2] == [None, None] and c1["series"][1]["y"][10:] == [None, None], ma)
b.num("最初の移動平均", ma[0], "28.375")
b.num("最後の移動平均", ma[-1], "34.375")
b.num("前の四半期との比", 30 / 48 - 1, "-0.375")
b.num("前年同期比", 30 / 27 - 1, "0.111")
b.num("前年同期比 %", (30 / 27 - 1) * 100, "11.1")
b.num("1→2 年目の成長率 %", (tot[1] / tot[0] - 1) * 100, "11.6")
b.num("2→3 年目の成長率 %", (tot[2] / tot[1] - 1) * 100, "11.2")
b.num("平均成長率", np.sqrt(tot[2] / tot[0]) - 1, "0.114")
# 寄与度
b.check("内訳の合計", 80 + 32 == 112 and 84 + 41 == 125, "")
b.num("店頭の寄与度 %", 4 / 112 * 100, "3.6")
b.num("通販の寄与度 %", 9 / 112 * 100, "8.0")
b.num("店頭の寄与率 %", 4 / 13 * 100, "30.8")
b.num("通販の寄与率 %", 9 / 13 * 100, "69.2")
b.num("通販自体の伸び %", 9 / 32 * 100, "28", tol=0.5)
# 指数
b.num("2 年目の指数", tot[1] / tot[0] * 100, "111.6")
b.num("3 年目の指数", tot[2] / tot[0] * 100, "124.1")
b.num("付け替え", (tot[2] / tot[0]) / (tot[1] / tot[0]) * 100, "111.2")
# 物価指数
p0, q0, p1, q1 = np.array([200, 100, 500]), np.array([10, 30, 4]), np.array([220, 100, 650]), np.array([9, 32, 3])
b.num("L の分子", (p1 * q0).sum(), "7800")
b.num("L の分母", (p0 * q0).sum(), "7000")
b.num("P の分子", (p1 * q1).sum(), "7130")
b.num("P の分母", (p0 * q1).sum(), "6500")
L, P = (p1 * q0).sum() / (p0 * q0).sum() * 100, (p1 * q1).sum() / (p0 * q1).sum() * 100
b.num("ラスパイレス", L, "111.4")
b.num("パーシェ", P, "109.7")
b.num("フィッシャー", np.sqrt(L * P), "110.6")
w = p0 * q0 / (p0 * q0).sum()
b.check("支出の割合 2/7・3/7・2/7", np.allclose(w, [2 / 7, 3 / 7, 2 / 7]), w)
b.num("加重平均の形", (w * p1 / p0).sum(), "1.114")
# 季節指数
r = y[2:10] / np.array(ma)
s = {3: (r[0] + r[4]) / 2, 4: (r[1] + r[5]) / 2, 1: (r[2] + r[6]) / 2, 2: (r[3] + r[7]) / 2}
k = 4 / sum(s.values())
sn = {q: v * k for q, v in s.items()}
for q, shown in [(1, "0.77"), (2, "1.01"), (3, "1.40"), (4, "0.83")]:
    b.num(f"季節指数 第{q}四半期", sn[q], shown)
adj = np.array([y[i] / sn[i % 4 + 1] for i in range(12)])
b.num("3 年目 10〜12 月の季節調整値", adj[11], "36.4")
b.check("3 年間で最も高い", adj[11] == adj.max(), adj.round(1))
b.num("本文の季節指数 0.825", sn[4], "0.825")
b.num("3 年目 7〜9 月の季節調整値", adj[10], "34.4")
b.num("本文の季節指数 1.397", sn[3], "1.397")
b.num("3 年目 4〜6 月の季節調整値", adj[9], "34.7")
# 自己相関
n, m = 12, y.mean()
c = lambda kk: ((y[:n - kk] - m) * (y[kk:] - m)).sum() / n
rk = [c(kk) / c(0) for kk in range(1, 9)]
b.num("平均", m, "31.33")
b.check("図2が計算と一致", np.allclose(b.chart(2)["values"], np.round(rk, 3), atol=1e-9), np.round(rk, 3))
b.num("r4", rk[3], "0.593")
b.num("r8", rk[7], "0.241")
b.num("r2", rk[1], "-0.507")
b.num("r6", rk[5], "-0.406")
# 章末問題
b.num("問1 前月比", 66 / 60 - 1, "0.10")
b.num("問1 前年同期比", 66 / 55 - 1, "0.20")
b.num("問1 倍率", 66 / 50, "1.32")
b.num("問1 平均成長率 %", (np.sqrt(1.32) - 1) * 100, "14.9")
b.num("問1 前半の伸び %", (55 / 50 - 1) * 100, "10")
b.num("問2 全体の成長率 %", 24 / 400 * 100, "6")
b.num("問2 国内の寄与度 %", -6 / 400 * 100, "-1.5")
b.num("問2 海外の寄与度 %", 30 / 400 * 100, "7.5")
b.num("問3 L", (120 * 20 + 60 * 40) / (100 * 20 + 50 * 40) * 100, "120")
b.num("問3 P", (120 * 15 + 60 * 50) / (100 * 15 + 50 * 50) * 100, "120")
b.check("問3 分子・分母 4800・4000", 120 * 15 + 60 * 50 == 4800 and 100 * 15 + 50 * 50 == 4000, "")
b.done()
