"""2級 教科書 第4章「単回帰と予測」の数値の検算。"""
import numpy as np
from bookcheck import Book

b = Book("g2", 4)
x = np.array([2, 3, 4, 5, 5, 6, 7, 8, 9, 11.])
y = np.array([48, 58, 50, 60, 66, 57, 72, 64, 79, 76.])
c1 = b.chart(1)
b.check("図1のデータ（第3章と同じ）", c1["x"] == list(x) and c1["y"] == list(y), "")
Sxx, Sxy, Syy = ((x - 6) ** 2).sum(), ((x - 6) * (y - 63)).sum(), ((y - 63) ** 2).sum()
b.check("S の値 70・225・980", (Sxx, Sxy, Syy) == (70, 225, 980), (Sxx, Sxy, Syy))
B = Sxy / Sxx
A = y.mean() - B * x.mean()
b.num("傾き", B, "3.214")
b.num("切片", A, "43.71")
b.num("傾き（式の表示）", B, "3.21")
b.check("np.polyfit と一致", np.allclose(np.polyfit(x, y, 1), [B, A]), np.polyfit(x, y, 1))
b.num("10 時間の予測", A + B * 10, "75.9")
b.num("丸めた傾きでの切片", 63 - 3.2 * 6, "43.8")
b.num("r s_y/s_x", np.corrcoef(x, y)[0, 1] * y.std(ddof=1) / x.std(ddof=1), "3.214")
e = y - (A + B * x)
for v, s in zip(e, ["-2.14", "4.64", "-6.57", "0.21", "6.21", "-6.00", "5.79", "-5.43", "6.36", "-3.07"]):
    b.num("残差", v, s)
b.check("残差の合計は 0", abs(e.sum()) < 1e-9, e.sum())
b.check("Σx e = 0", abs((x * e).sum()) < 1e-9, (x * e).sum())
b.num("残差平方和", (e ** 2).sum(), "256.8")
b.check("残差平方和 = Syy − Sxy²/Sxx", abs((e ** 2).sum() - (Syy - Sxy ** 2 / Sxx)) < 1e-9, "")
b.check("変動の分解", abs(Syy - (((A + B * x - 63) ** 2).sum() + (e ** 2).sum())) < 1e-9, "")
R2 = 1 - (e ** 2).sum() / Syy
b.num("決定係数", R2, "0.738")
b.check("R² = r²", abs(R2 - np.corrcoef(x, y)[0, 1] ** 2) < 1e-12, "")
b.num("説明できる割合 %", R2 * 100, "74", tol=0.5)
b.num("0 時間の予測", A, "43.7")
b.num("30 時間の予測", A + B * 30, "140.1")
bx = Sxy / Syy
b.num("x を y に回帰した傾き", bx, "0.230")
b.num("その切片", 6 - bx * 63, "-8.46")
b.num("逆に解いた y の傾き", 1 / bx, "4.36")
# 利用者数
t = np.arange(7.)
u = np.array([10, 15, 22, 34, 50, 76, 113.])
b.check("本文の利用者数", b.has("10、15、22、34、50、76、113"), "")
L1 = np.polyfit(t, u, 1)
b.num("直線の傾き", L1[0], "16.39")
b.num("直線の切片", L1[1], "-3.46")
b.num("直線の決定係数", np.corrcoef(t, u)[0, 1] ** 2, "0.898")
res = u - np.polyval(L1, t)
c2 = b.chart(2)
b.check("図2の残差が計算と一致", np.allclose(c2["y"], res.round(2), atol=1e-9) and c2["x"] == list(range(7)), res.round(2))
for v, s in zip(res, ["13.46", "2.07", "-7.32", "-11.71", "-12.11", "-2.5", "18.11"]):
    b.num("直線の残差", v, s)
b.num("15/10", 15 / 10, "1.5")
b.num("22/15", 22 / 15, "1.47")
lg = np.log10(u)
c3 = b.chart(3)
b.check("図3の対数が計算と一致", np.allclose(c3["y"], lg.round(3), atol=1e-9), lg.round(3))
L2 = np.polyfit(t, lg, 1)
b.num("対数の傾き", L2[0], "0.176")
b.num("対数の決定係数", np.corrcoef(t, lg)[0, 1] ** 2, "0.9999")
b.num("1 年の倍率", 10 ** L2[0], "1.50")
b.num("7 年目の予測（対数）", 10 ** np.polyval(L2, 7), "170", tol=1)
b.num("7 年目の予測（直線）", np.polyval(L1, 7), "111")
# 章末問題
px, py = np.array([1, 2, 3, 4, 5.]), np.array([3, 4, 8, 9, 11.])
sxx, sxy, syy = ((px - 3) ** 2).sum(), ((px - 3) * (py - 7)).sum(), ((py - 7) ** 2).sum()
b.check("問1 S の値 10・21・46", (sxx, sxy, syy) == (10, 21, 46), (sxx, sxy, syy))
b.num("問1 傾き", sxy / sxx, "2.1")
b.num("問1 切片", 7 - 2.1 * 3, "0.7")
b.num("問1 決定係数", sxy ** 2 / (sxx * syy), "0.959")
b.num("問2 傾き", 0.6 * 15 / 12, "0.75")
b.num("問2 切片", 55 - 0.75 * 60, "10")
b.num("問2 予測", 10 + 0.75 * 80, "70")
b.num("問2 決定係数", 0.36, "0.36")
b.num("問2 標準偏差何個分", 20 / 12, "1.67")
b.num("問4 倍率", 322 / 200, "1.61")
b.num("問4 log10 1.61", np.log10(1.61), "0.2068")
b.num("問4 log10 k（与えた近似値 0.2068 から）", 0.2068 / 5, "0.04136")
b.num("問4 与えた 10^0.04136", 10 ** 0.04136, "1.100")
b.num("問4 k", 10 ** (np.log10(1.61) / 5), "1.100")
b.check("問4 1.1⁵×200 ≈ 322", abs(200 * 1.1 ** 5 - 322) < 0.5, 200 * 1.1 ** 5)
b.done()
