def main():
    old = {}
    if OUT.exists():
        for ch in yaml.safe_load(OUT.read_text(encoding="utf-8"))["chapters"]:
            for t in ch["terms"]:
                old[t["id"]] = t["status"]
    src_plans = {"g2": {c["no"]: c for c in G2["chapters"]}, "pre1": {c["no"]: c for c in PRE1["chapters"]}}
    used, chapters = set(), []
    for title, src, nos, lead in UNDERGRAD:
        terms = []
        for no in nos:
            for t in src_plans[src][no]["terms"]:
                if t.get("see") or t["id"] in used:
                    continue
                used.add(t["id"])
                terms.append({"id": t["id"], "title": t["title"], "importance": t["importance"], "status": t["status"], "from": src})
        chapters.append({"no": len(chapters) + 1, "title": title, "lead": lead, "terms": terms})
    for title, lead, items in GRAD:
        for tid, _, _ in items:
            assert tid not in used, tid
            used.add(tid)
        chapters.append({"no": len(chapters) + 1, "title": title, "lead": lead,
                         "terms": [{"id": tid, "title": tt, "importance": imp, "status": old.get(tid, "planned")} for tid, tt, imp in items]})
    head = "# 統計学の教科書（学部1年〜修士2年）の用語計画。scripts/make_plan_tb.py が作る（直接書き換えない）。\n# from: g2 / pre1 は2級・準1級の解説を共通で使う用語。from のない用語は content/tb/chNN/ に教科書のために書いた解説。\n"
    OUT.write_text(head + yaml.safe_dump({"chapters": chapters}, allow_unicode=True, sort_keys=False, width=200), encoding="utf-8")
    n_sh = sum(1 for c in chapters for t in c["terms"] if t.get("from"))
    n_own = sum(1 for c in chapters for t in c["terms"] if not t.get("from"))
    print(f"章 {len(chapters)}（学部 {len(UNDERGRAD)}・大学院 {len(GRAD)}）/ 共通の用語 {n_sh} / 教科書で書く用語 {n_own}")
    for c in chapters:
        print(c["no"], c["title"], len(c["terms"]))


if __name__ == "__main__":
    main()
